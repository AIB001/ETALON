"""Rebind portable host exports to an explicit runtime and research entry.

The recipe travels with the package. Machine bindings are generated by the
Python running install. Only hash-verified owned files can be replaced.
Installation never edits trust, global configuration, or scientific evidence.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import tempfile


def _identity(data):
    return {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}


def _io(path):
    """Extended Windows paths only at the filesystem boundary, not in identities."""
    path = Path(path).absolute()
    value = str(path)
    if os.name == "nt" and not value.startswith("\\\\?\\"):
        return Path("\\\\?\\UNC\\" + value[2:]) if value.startswith("\\\\") else Path("\\\\?\\" + value)
    return path


def _write(path, data):
    path = _io(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".etalon-install-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def _read(path):
    path = _io(path)
    if path.stat().st_size > 4 * 1024 * 1024:
        raise ValueError("installation metadata exceeds 4 MiB")
    return path.read_bytes()


def _immutable(path, data):
    if _io(path).exists():
        if _read(path) != data:
            raise ValueError("saved installation intent or backup conflicts")
    else:
        _write(path, data)


def _intent(archive, adapter):
    return json.loads(_read(archive / "intent.json"))


def _finish(archive, intent, adapter):
    _immutable(archive / "receipt.json", adapter._json({**intent, "status": "complete"}))


def _initial(root, entry, host, hook_transport, adapter, selected_skills=None):
    """Publish a complete new directory; preserve a resumable sibling staging area."""
    config = {"entry": str(entry), "state_dir": str(root / ".etalon/research-hook-receipts"),
              "launcher": str(root / ".etalon/research-hook.py")}
    current, files = adapter._payload(host, config, hook_transport=hook_transport, portable=True,
                                     selected_skills=selected_skills)
    new_bytes = adapter._json(current)
    stage = adapter._root(root.parent / (".etalon-install-" + hashlib.sha256(str(root).encode()).hexdigest()[:24]))
    operation = hashlib.sha256(b"initial\0" + new_bytes).hexdigest()
    relative = ".etalon/installations/" + operation
    intent = {"schema": "etalon-host-install-operation/1", "operation_id": operation,
              "kind": "initial", "target": str(root), "previous_manifest": None,
              "next_manifest": _identity(new_bytes)}
    archive = adapter._member(stage, relative)
    if _io(stage).exists():
        if not any(path.is_file() for path in _io(stage).rglob("*")):
            # No owned file was written yet: this covers death after mkdir but
            # before the first atomic intent write. No arbitrary project is used.
            _immutable(archive / "intent.json", adapter._json(intent))
        elif not _io(archive / "intent.json").is_file() or _intent(archive, adapter) != intent:
            raise ValueError("unfinished initial installation does not match this request; retain it for review")
    else:
        _io(stage).mkdir(parents=True, exist_ok=False)
        _immutable(archive / "intent.json", adapter._json(intent))
    for name, data in {**files, adapter.MANIFEST: new_bytes}.items():
        path = adapter._member(stage, name)
        if _io(path).exists() and _read(path) != data:
            raise ValueError("modified staging member must be reviewed before install: " + name)
    allowed = {*files, adapter.MANIFEST, relative + "/intent.json"}
    for path in _io(stage).rglob("*"):
        if path.is_file():
            name = path.relative_to(_io(stage)).as_posix()
            if name not in allowed and not path.name.startswith(".etalon-install-"):
                raise ValueError("unexpected initial staging member: " + name)
    for name, data in files.items():
        _immutable(adapter._member(stage, name), data)
    _immutable(adapter._member(stage, adapter.MANIFEST), new_bytes)
    os.rename(_io(stage), _io(root))
    verification = adapter.verify(root)
    if not all(verification[k] for k in ("export_matches_manifest", "matches_current_source", "runtime_matches")):
        raise ValueError("initial installation verification failed")
    final_archive = adapter._member(root, relative)
    _finish(final_archive, intent, adapter)
    return {"status": "installed", "changed": True, "target": str(root),
            "manifest": str(root / adapter.MANIFEST), **current, "verification": verification,
            "operation": str(final_archive), "native_activation": "requires_host_discovery_and_trust_review"}


def install(target, *, research_entry, host="codex", hook_transport="mcp_tool", selected_skills=None):
    """Create a project or rebind an unchanged portable export after moving it.

    No dependency installation or shared-runtime upgrade is implicit. Existing
    arbitrary projects are refused. Repeated exact installs are no-ops.
    """
    from etalon import host as adapter
    root = adapter._root(target)
    entry = adapter._root(research_entry)
    if not entry.is_file():
        raise ValueError("research entry must be an existing explicit server-local JSON file")
    _io(root.parent).mkdir(parents=True, exist_ok=True)
    lock = root.parent / (".etalon-install-" + hashlib.sha256(str(root).encode()).hexdigest()[:24] + "-writer")
    with adapter._consumer_lock(_io(lock)):
        if not _io(root).exists():
            return _initial(root, entry, host, hook_transport, adapter, selected_skills)
        manifest_path = adapter._member(root, adapter.MANIFEST)
        if not _io(manifest_path).is_file():
            raise ValueError("existing project is not an ETALON export; choose a new adapter directory")
        old_bytes = _read(manifest_path)
        if len(old_bytes) > 4 * 1024 * 1024:
            raise ValueError("host manifest exceeds 4 MiB")
        old = json.loads(old_bytes)
        if old.get("schema") != "etalon-host-export/1" or not old.get("portable"):
            raise ValueError("rebind requires a portable ETALON export")
        if old.get("host") != host:
            raise ValueError("install host differs; use a separate project for another host")
        if selected_skills is not None and selected_skills != old.get("selected_skills"):
            raise ValueError("install skill selection differs; export a new adapter version")
        selected_skills = old.get("selected_skills")
        workset = None
        if "task_workset_digest" in old:
            workset = json.loads(_read(adapter._member(root, ".etalon/task-workset.json")))
            if workset.get("digest") != old["task_workset_digest"]:
                raise ValueError("exported workset identity mismatch")
        config = {"entry": str(entry), "state_dir": str(root / ".etalon/research-hook-receipts"),
                  "launcher": str(root / ".etalon/research-hook.py")}
        current, files = adapter._payload(host, config, workset,
                                          hook_transport=hook_transport, portable=True,
                                          selected_skills=selected_skills)
        new_bytes = adapter._json(current)
        pending = None
        installation_root = adapter._member(root, ".etalon/installations")
        if _io(installation_root).exists():
            for path in _io(installation_root).glob("*/intent.json"):
                archive = installation_root / path.parent.name
                candidate = _intent(archive, adapter)
                if _io(archive / "receipt.json").exists():
                    continue
                if candidate.get("schema") != "etalon-host-install-operation/1":
                    raise ValueError("unrecognized unfinished installation")
                if _identity(old_bytes) not in (candidate.get("previous_manifest"), candidate.get("next_manifest")):
                    continue
                if candidate.get("next_manifest") != _identity(new_bytes):
                    raise ValueError("unfinished installation does not match requested configuration")
                if pending is not None:
                    raise ValueError("multiple unfinished installations require explicit review")
                pending = (archive, candidate)
        names = set(old.get("files", {})) | set(files)
        if not names or len(names) > 2000:
            raise ValueError("invalid portable export inventory")
        if set(old["files"]) - set(files):
            raise ValueError("install would remove owned files; export a new adapter version")
        for name in names:
            path = adapter._member(root, name)
            actual = _identity(_read(path)) if _io(path).is_file() else None
            allowed = [old["files"].get(name), _identity(files[name])]
            if actual not in allowed:
                raise ValueError(f"modified export member must be reviewed before install: {name}")
        directory = ".agents/skills" if host == "codex" else ".claude/skills"
        for prefix in (directory, "host-guides"):
            parent = adapter._member(root, prefix)
            if parent.exists():
                for path in parent.rglob("*"):
                    member = path.relative_to(root).as_posix()
                    adapter._member(root, member)
                    if path.is_file() and member not in names:
                        raise ValueError(f"unexpected export member: {member}")
        if old_bytes == new_bytes:
            verification = adapter.verify(root)
            if not all(verification[k] for k in ("export_matches_manifest", "matches_current_source", "runtime_matches")):
                raise ValueError("existing installation verification failed")
            if pending is not None:
                _finish(*pending, adapter)
                return {"status": "recovered", "changed": True, "target": str(root),
                        "operation": str(pending[0]), "verification": verification,
                        "native_activation": "not_inferred_from_installation"}
            return {"status": "already_installed", "changed": False, "target": str(root),
                    "verification": verification,
                    "native_activation": "not_inferred_from_installation"}
        operation = hashlib.sha256(old_bytes + new_bytes).hexdigest()
        archive = adapter._member(root, ".etalon/installations/" + operation)
        _io(archive).mkdir(parents=True, exist_ok=True)
        intent = {"schema": "etalon-host-install-operation/1", "operation_id": operation,
                  "previous_manifest": _identity(old_bytes), "next_manifest": _identity(new_bytes)}
        if pending is not None:
            archive, intent = pending
        _immutable(archive / "intent.json", adapter._json(intent))
        # Keep previous generated bytes; receipts and research remain untouched.
        for name in [adapter.MANIFEST, *sorted(names)]:
            path = adapter._member(root, name)
            backup = archive / "before" / name
            if _io(path).is_file() and not _io(backup).exists():
                _write(backup, _read(path))
        for name, data in files.items():
            path = adapter._member(root, name)
            if not _io(path).is_file() or _read(path) != data:
                _write(path, data)
        _write(manifest_path, new_bytes)
        verification = adapter.verify(root)
        if not all(verification[k] for k in (
                "export_matches_manifest", "matches_current_source", "runtime_matches")):
            raise ValueError("installed export verification failed")
        _finish(archive, intent, adapter)
        return {"status": "rebound", "changed": True, "target": str(root),
                "operation": str(archive), "verification": verification,
                "native_activation": "review_changed_definitions_in_native_host"}


def doctor(target):
    """Mechanical configuration check, explicitly not native activation."""
    from etalon import host as adapter
    root = adapter._root(target)
    verification = adapter.verify(root)
    saved = json.loads(adapter._member(root, adapter.MANIFEST).read_bytes())
    transport = saved.get("hook_transport", "command")
    binding = None
    if transport == "mcp_tool":
        binding = json.loads(adapter._member(root, ".etalon/research-hook-binding.json").read_bytes())
    good = all(verification[key] for key in (
        "export_matches_manifest", "matches_current_source", "runtime_matches"))
    entry = (binding or saved.get("research_hooks", {})).get("entry")
    hooks_path = adapter._member(root,
        ".codex/hooks.json" if saved["host"] == "codex" else ".claude/settings.json")
    events = list(json.loads(_read(hooks_path)).get("hooks", {})) if _io(hooks_path).is_file() else []
    return {"schema": "etalon-host-doctor/1", "configuration_verified": good,
            "verification_stages": {
                "static_installation": "verified" if good else "mismatch",
                "app_server": "not_checked", "native_discovery": "not_checked",
                "host_review": "not_checked", "login": "not_checked",
                "mcp_reachability": "not_checked", "native_event_acceptance": "not_verified",
                "model_consumption": "not_verified"},
            "acceptance_complete": False,
            "host": saved["host"], "transport": transport, "verification": verification,
            "entry_exists_on_server": bool(entry and Path(entry).is_file()),
            "configured_events": events,
            "startup_delivery": "MCP may not be ready; first matching PreToolUse prepares baseline"
                if transport == "mcp_tool" else "command_adapter",
            "native_discovery": "not_checked", "native_trust": "not_checked",
            "native_delivery": "not_verified", "model_consumption": "not_verified",
            "scientific_execution_permission": "not_granted"}
